# =============================================================================
# G1 RL 训练参数配置文件
# =============================================================================
# 所有用户可调的参数都在这里，按功能（train/play）划分。
# 修改后直接生效，不需要设环境变量，不需要改 CLI 参数。
#
# 使用方式（在容器内）：
#   from g1_config import G1_CONFIG
#   num_envs = G1_CONFIG.train.num_envs
# =============================================================================


class TrainConfig:
    """训练 (train / train-gui / resume) 参数"""

    # ── 任务名称 ───────────────────────────────────────────────────────
    task = "Unitree-G1-29dof-Velocity"

    # ── 并行环境数 ──────────────────────────────────────────────────────
    # 每个环境里有一个机器人，越大训练越快但显存消耗越多
    # 16GB 显存推荐 4096，14GB 内存推荐不超过 4096
    num_envs = 4096

    # ── 训练迭代次数 ────────────────────────────────────────────────────
    # 一个 iteration = 24 步 × num_envs 个环境
    max_iterations = 50000

    # ── 随机种子 ────────────────────────────────────────────────────────
    # -1 表示每次启动随机生成
    seed = 43


class PlayConfig:
    """回放 (play) 参数"""

    # ── 任务名称 ───────────────────────────────────────────────────────
    task = "Unitree-G1-29dof-Velocity"

    # ── 并行环境数 ──────────────────────────────────────────────────────
    # 回放时通常用较少环境，方便观察机器人行为
    num_envs = 8


class DeployConfig:
    """真机部署 (deploy) 参数"""

    # ── 训练 Run 名称 ────────────────────────────────────────────────────
    # logs/rsl_rl/unitree_g1_29dof_velocity/ 下的时间戳目录名
    run_name = "2026-06-24_09-29-56"

    # ── Checkpoint 文件名 ──────────────────────────────────────────────────
    # 要导出为 ONNX 的模型 checkpoint
    checkpoint = "model_18100"

    # ── 机器人 IP 地址 ─────────────────────────────────────────────────────
    # G1 机器人无线网卡的 IP（通过 ifconfig 查看）
    robot_ip = "192.168.123.161"

    # ── 机器人上的部署路径 ─────────────────────────────────────────────────
    # deploy/ 目录会被 rsync 到这个路径
    robot_deploy_path = "~/g1-rl-deploy"


class G1Config:
    """G1 训练总配置 — 按功能分组"""
    train = TrainConfig()
    play = PlayConfig()
    deploy = DeployConfig()


# 全局单例，导入即用
G1_CONFIG = G1Config()
